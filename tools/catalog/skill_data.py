#!/usr/bin/env python3
"""Turn shared CraftPilot skill notes into confirmed colour ranges.

Players copy a code from CraftPilot (Hilfe > Skilldaten teilen) and post it in the CraftPilot Discord; the bot
files each post as a GitHub issue with the label `skilldaten`. This tool reads those codes (an issue export from
`gh issue list --json number,body` and/or plain text files), adds them up per recipe and skill and writes

  Data/Catalog/Observed.lua   CP.ObservedSkill[key][spell] = {crafts, points, lastPoint, greyFrom, status}
  docs/SKILL_DATA.md          a readable report: confirmed, contradicting and still open recipes

Code format: CPSKILL1;<client build>;key:spell:skill:crafts:points,...  Identical codes count once.

status: "confirmed"  points were seen up to grey-1 and none in >= 5 crafts at or above the catalog's grey
        "conflict"   a point came at or above the catalog's grey (the catalog's grey is too low)
        "open"       not enough crafts around grey yet

  python3 tools/catalog/skill_data.py --issues issues.json [--text more.txt ...]
"""
import argparse
import hashlib
import json
import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CODE = re.compile(r'CPSKILL1;([^;\s]*);([a-z]+:\d+:\d+:\d+:\d+(?:,[a-z]+:\d+:\d+:\d+:\d+)*)')
RECIPE = re.compile(r'\[(\d+)\] = \{ name = "((?:[^"\\]|\\.)*)".*?colors = \{ (\d+), (\d+), (\d+), (\d+) \}')
MIN_GREY_CRAFTS = 5


def codes(texts):
    seen = set()
    for text in texts:
        for m in CODE.finditer(text or ''):
            digest = hashlib.sha256(m.group(0).encode()).hexdigest()
            if digest in seen:
                continue
            seen.add(digest)
            yield m.group(1), m.group(2)


def collect(texts):
    data = defaultdict(lambda: defaultdict(lambda: defaultdict(lambda: [0, 0])))
    builds = set()
    for build, body in codes(texts):
        builds.add(build)
        for entry in body.split(','):
            key, spell, skill, n, u = entry.split(':')
            n, u = int(n), int(u)
            if n <= 0 or u < 0 or u > n:
                continue
            cell = data[key][int(spell)][int(skill)]
            cell[0] += n
            cell[1] += u
    return data, builds


def catalog_colors():
    out = {}
    for path in sorted((ROOT / 'Data' / 'Catalog').glob('*.lua')):
        key = None
        for line in path.read_text(encoding='utf-8').splitlines():
            k = re.match(r'CP\.CatalogData\.(\w+) = \{', line)
            if k:
                key = k.group(1)
            m = RECIPE.search(line)
            if key and m:
                out[(key, int(m.group(1)))] = (m.group(2), [int(m.group(i)) for i in range(3, 7)])
    return out


def judge(skills, grey):
    crafts = sum(c[0] for c in skills.values())
    points = sum(c[1] for c in skills.values())
    with_point = [s for s, c in skills.items() if c[1] > 0]
    last_point = max(with_point) if with_point else None
    at_grey = sum(c[0] for s, c in skills.items() if grey is not None and s >= grey)
    grey_points = sum(c[1] for s, c in skills.items() if grey is not None and s >= grey)
    # Lowest skill from which on no point came in enough crafts.
    grey_from = None
    for s in sorted(skills, reverse=True):
        if skills[s][1] > 0:
            break
        grey_from = s
    if grey is None:
        status = 'open'
    elif grey_points > 0:
        status = 'conflict'
    elif at_grey >= MIN_GREY_CRAFTS and last_point is not None and last_point >= grey - 5:
        status = 'confirmed'
    else:
        status = 'open'
    return {'crafts': crafts, 'points': points, 'lastPoint': last_point, 'greyFrom': grey_from, 'status': status}


def write_lua(results, builds, out):
    lines = ['-- CraftPilot: skill colours confirmed by players. GENERATED by tools/catalog/skill_data.py - do not edit.',
             '-- From shared CraftPilot skill notes (Hilfe > Skilldaten teilen); client builds: ' + (', '.join(sorted(builds)) or '-') + '.',
             'local _, CP = ...',
             'CP.ObservedSkill = {']
    for key in sorted(results):
        lines.append('  %s = {' % key)
        for spell in sorted(results[key]):
            r = results[key][spell]
            fields = ['crafts = %d' % r['crafts'], 'points = %d' % r['points'], 'status = "%s"' % r['status']]
            if r['lastPoint'] is not None:
                fields.append('lastPoint = %d' % r['lastPoint'])
            if r['greyFrom'] is not None:
                fields.append('greyFrom = %d' % r['greyFrom'])
            lines.append('    [%d] = { %s },' % (spell, ', '.join(fields)))
        lines.append('  },')
    lines.append('}')
    out.write_text('\n'.join(lines) + '\n', encoding='utf-8')


def write_report(results, colors, builds, out):
    count = defaultdict(int)
    rows = []
    for key in sorted(results):
        for spell in sorted(results[key]):
            r = results[key][spell]
            count[r['status']] += 1
            name, c = colors.get((key, spell), ('?', None))
            rows.append('| %s | %s (%d) | %s | %d | %d | %s | %s | %s |' % (
                r['status'], name, spell, key, r['crafts'], r['points'], r['lastPoint'] if r['lastPoint'] is not None else '–',
                r['greyFrom'] if r['greyFrom'] is not None else '–', '/'.join(map(str, c)) if c else '–'))
    text = ['# Skilldaten aus der Community', '',
            'Erzeugt von `tools/catalog/skill_data.py` aus den geteilten CraftPilot-Codes (Issues mit Label `skilldaten`).', '',
            'Client-Builds: ' + (', '.join(sorted(builds)) or '–'), '',
            '- bestätigt (confirmed): %d' % count['confirmed'],
            '- widersprüchlich (conflict): %d – ein Punkt kam bei oder über dem Grau des Katalogs' % count['conflict'],
            '- offen (open): %d – noch zu wenige Herstellungen rund um Grau' % count['open'], '',
            '| Status | Rezept | Beruf | Herstellungen | Punkte | letzter Punkt bei | ohne Punkt ab | Katalog o/y/g/grau |',
            '| --- | --- | --- | --- | --- | --- | --- | --- |'] + rows
    out.write_text('\n'.join(text) + '\n', encoding='utf-8')


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--issues', type=Path, help='JSON from gh issue list --json number,body')
    p.add_argument('--text', type=Path, nargs='*', default=[], help='plain text files with codes')
    p.add_argument('--lua', type=Path, default=ROOT / 'Data' / 'Catalog' / 'Observed.lua')
    p.add_argument('--report', type=Path, default=ROOT / 'docs' / 'SKILL_DATA.md')
    args = p.parse_args()
    texts = []
    if args.issues:
        texts += [i.get('body') or '' for i in json.loads(args.issues.read_text(encoding='utf-8'))]
    texts += [t.read_text(encoding='utf-8') for t in args.text]
    data, builds = collect(texts)
    colors = catalog_colors()
    results = {key: {spell: judge(skills, (colors.get((key, spell), (None, None))[1] or [None] * 4)[3])
                     for spell, skills in spells.items()} for key, spells in data.items()}
    write_lua(results, builds, args.lua)
    write_report(results, colors, builds, args.report)
    print('skill data: %d recipes from %d codes' % (sum(len(s) for s in results.values()), len(list(codes(texts)))))


if __name__ == '__main__':
    main()
