"""Build Data/Maps/MapOverlays.lua: the detail pieces of every zone map (towns, roads, forests) from the
WoW Forever client's own tables as wago.tools publishes them, so CraftPilot's map window can show the whole map.

    python3 tools/maps/build_overlays.py [--build 1.60.1.xxxxx] [--out Data/Maps/MapOverlays.lua]

Tables: UiMapXMapArt (zone -> map art), WorldMapOverlay (pieces of a map art: size and offset) and
WorldMapOverlayTile (the texture file of each 256 px tile). Runs in GitHub Actions (by hand when the client changes);
the build is the newest Forever build (wowf), as in CraftPilot's catalog.
"""
import argparse
import csv
import io
import json
import sys
import time
import urllib.request
from pathlib import Path

UA = 'CraftPilot-maps/1.0 (+https://github.com/Necrite82/CraftPilot)'
BUILDS = 'https://wago.tools/api/builds'
DB2 = 'https://wago.tools/db2/{table}/csv?build={build}'
ROOT = Path(__file__).resolve().parents[2]


def get(url, tries=4):
    for attempt in range(tries):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers={'User-Agent': UA}), timeout=300) as r:
                return r.read()
        except Exception as err:
            if attempt == tries - 1:
                raise
            print(f'  retry {attempt + 1} for {url}: {err}', file=sys.stderr)
            time.sleep(5 * (attempt + 1))


def newest(builds, branches, prefix):
    found = [b['version'] for branch in branches for b in builds.get(branch, []) if b['version'].startswith(prefix)]
    if not found:
        raise SystemExit(f'wago.tools lists no {prefix}* build on {branches}; branches: {sorted(builds)}')
    return max(found, key=lambda v: tuple(int(x) for x in v.split('.')))


def table(name, build):
    data = get(DB2.format(table=name, build=build))
    if not data.strip() or data.lstrip()[:1] == b'<':
        raise SystemExit(f'wago.tools sent no CSV for {name} @ {build}')
    rows = list(csv.DictReader(io.StringIO(data.decode('utf-8-sig'))))
    print(f'  {name}: {len(rows)} rows, columns {list(rows[0].keys()) if rows else []}')
    return rows


def col(row, *names):
    """Column by any of its names, case-insensitive (wago's names vary a little between tables)."""
    lower = {k.lower(): v for k, v in row.items()}
    for name in names:
        if name.lower() in lower and lower[name.lower()] not in (None, ''):
            return int(float(lower[name.lower()]))
    return None


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--build')
    ap.add_argument('--out', type=Path, default=ROOT / 'Data' / 'Maps' / 'MapOverlays.lua')
    args = ap.parse_args()
    build = args.build or newest(json.loads(get(BUILDS)), ('wowf', 'wow_classic_beta'), '1.6')
    print(f'Forever build {build}')
    links = table('UiMapXMapArt', build)
    overlays = table('WorldMapOverlay', build)
    tiles = table('WorldMapOverlayTile', build)

    arts = {}
    for row in links:
        ui_map, art = col(row, 'UiMapID'), col(row, 'UiMapArtID')
        phase = col(row, 'PhaseID') or 0
        if ui_map and art and phase == 0:
            arts.setdefault(art, set()).add(ui_map)
    pieces = {}
    for row in overlays:
        oid, art = col(row, 'ID'), col(row, 'UiMapArtID')
        width, height = col(row, 'TextureWidth'), col(row, 'TextureHeight')
        if oid and art in arts and width and height:
            pieces[oid] = {'art': art, 'x': col(row, 'OffsetX') or 0, 'y': col(row, 'OffsetY') or 0,
                           'w': width, 'h': height, 'tiles': {}}
    for row in tiles:
        oid = col(row, 'WorldMapOverlayID')
        if oid in pieces and (col(row, 'LayerIndex') or 0) == 0:
            pieces[oid]['tiles'][(col(row, 'RowIndex') or 0, col(row, 'ColIndex') or 0)] = col(row, 'FileDataID')

    maps = {}
    for oid in sorted(pieces):
        piece = pieces[oid]
        columns = -(-piece['w'] // 256)
        rows = -(-piece['h'] // 256)
        files = [piece['tiles'].get((r, c)) or 0 for r in range(rows) for c in range(columns)]
        if not any(files):
            continue
        for ui_map in sorted(arts[piece['art']]):
            maps.setdefault(ui_map, []).append((piece['x'], piece['y'], piece['w'], piece['h'], files))

    lines = [
        '-- CraftPilot map pieces: every detail piece of the zone maps (WorldMapOverlay), from the WoW Forever client',
        '-- tables (wago.tools). GENERATED by tools/maps/build_overlays.py - do not edit.',
        'local _, CP = ...',
        'CP.MapOverlays = {',
        f'  source = "{build}",',
        '  maps = {',
    ]
    for ui_map in sorted(maps):
        lines.append(f'    [{ui_map}] = {{')
        for x, y, w, h, files in maps[ui_map]:
            lines.append(f'      {{ {x}, {y}, {w}, {h}, {{ {", ".join(str(f) for f in files)} }} }},')
        lines.append('    },')
    lines += ['  },', '}']
    args.out.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    count = sum(len(v) for v in maps.values())
    print(f'MapOverlays.lua: {len(maps)} maps, {count} pieces')
    if len(maps) < 10:
        raise SystemExit('Too few maps: the table layout may have changed')


if __name__ == '__main__':
    main()
