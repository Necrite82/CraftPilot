"""Build ThirdParty/Gathering/Gathering.lua: where ores, stones and herbs of WoW Forever can be gathered.

For every ore, stone and herb, the zones with the most gathering nodes that yield it, how many nodes QuestieDB knows
there and the skill the node needs. Inputs: QuestieDB's Forever item data (which objects drop an item), object data
(where the objects stand) and its area -> UiMap table, pinned in ThirdParty/Gathering/SOURCES.json by commit and SHA-256.
The skill a node needs is the classic gathering requirement (a fact of the game, listed below).

    python3 tools/import_gathering.py --questiedb DIR [--check]
"""
import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'ThirdParty' / 'Gathering'
ITEM_FILE = 'data/Forever/foreverItemDB.lua'
OBJECT_FILE = 'data/Forever/foreverObjectDB.lua'
ZONE_FILE = 'support/Forever/Zones/areaIdToUiMapId.lua'
TOP_ZONES = 4

MINING = {
    'Copper Vein': 1, 'Tin Vein': 65, 'Incendicite Mineral Vein': 65, 'Silver Vein': 75, 'Ooze Covered Silver Vein': 75,
    'Lesser Bloodstone Deposit': 75, 'Iron Deposit': 125, 'Indurium Mineral Vein': 150, 'Gold Vein': 155,
    'Ooze Covered Gold Vein': 155, 'Mithril Deposit': 175, 'Ooze Covered Mithril Deposit': 175, 'Truesilver Deposit': 230,
    'Ooze Covered Truesilver Deposit': 230, 'Dark Iron Deposit': 230, 'Small Thorium Vein': 245,
    'Ooze Covered Thorium Vein': 245, 'Rich Thorium Vein': 275, 'Ooze Covered Rich Thorium Vein': 275,
    'Hakkari Thorium Vein': 275,
}
HERBALISM = {
    'Peacebloom': 1, 'Silverleaf': 1, 'Earthroot': 15, 'Mageroyal': 50, 'Briarthorn': 70, 'Stranglekelp': 85,
    'Bruiseweed': 100, 'Wild Steelbloom': 115, 'Grave Moss': 120, 'Kingsblood': 125, 'Liferoot': 150, 'Fadeleaf': 160,
    'Goldthorn': 170, "Khadgar's Whisker": 185, 'Wintersbite': 195, 'Firebloom': 205, 'Purple Lotus': 210,
    "Arthas' Tears": 220, 'Sungrass': 230, 'Blindweed': 235, 'Ghost Mushroom': 245, 'Gromsblood': 250,
    'Golden Sansam': 260, 'Dreamfoil': 270, 'Mountain Silversage': 280, 'Plaguebloom': 285, 'Icecap': 290,
    'Black Lotus': 300,
}
STONES = re.compile(r'^(Rough|Coarse|Heavy|Solid|Dense) Stone$')


def sha(data):
    return hashlib.sha256(data).hexdigest()


def table_body(text, name):
    m = re.search(r'QuestieDB\.' + name + r' = \[\[return \{(.*)\n\}\]\]', text, re.S)
    if not m:
        raise SystemExit('No ' + name + ' table')
    return m.group(1)


def objects(text):
    """object id -> (name, {area: node count}) for the gathering nodes listed above."""
    out = {}
    for line in table_body(text, 'objectData').split('\n'):
        m = re.match(r'\[(\d+)\] = \{"((?:[^"\\]|\\.)*)",', line)
        if not m:
            continue
        name = m.group(2).replace('\\"', '"')
        if name not in MINING and name not in HERBALISM:
            continue
        counts = {}
        spawns = re.search(r'\{(\[\d+\]=\{.*?\}\})\}', line[m.end():])
        if spawns:
            for area, coords in re.findall(r'\[(\d+)\]=\{((?:\{[^{}]*\},?)*)\}', spawns.group(1)):
                n = len(re.findall(r'\{[^{}]*\}', coords))
                if n:
                    counts[int(area)] = counts.get(int(area), 0) + n
        out[int(m.group(1))] = (name, counts)
    return out


def items(text, nodes):
    """item id -> (name, [object ids]) for ores, stones and herbs dropped by a known node."""
    out = {}
    for line in table_body(text, 'itemData').split('\n'):
        m = re.match(r"\[(\d+)\] = \{'((?:[^'\\]|\\.)*)',(nil|\{[^{}]*\}),(nil|\{[^{}]*\}),", line)
        if not m or m.group(4) == 'nil':
            continue
        name = m.group(2).replace("\\'", "'")
        if not (name.endswith(' Ore') or STONES.match(name) or name in HERBALISM):
            continue
        drops = [int(o) for o in re.findall(r'\d+', m.group(4)) if int(o) in nodes]
        if drops:
            out[int(m.group(1))] = (name, drops)
    return out


def zone_maps(text):
    maps = {}
    for part in ('areaIdToUiMapId', 'areaIdToUiMapIdOverride'):
        m = re.search(r'ZoneDB\.private\.' + part + r' = \[\[return \{(.*?)\n\}\]\]', text, re.S)
        for area, ui, name in re.findall(r'\[(\d+)\]\s*=\s*(\d+),?\s*(?:--\s*([^\n]*))?', m.group(1) if m else ''):
            if int(ui) > 0:
                maps[int(area)] = (int(ui), (name or '').strip())
            else:
                maps.pop(int(area), None)
    return maps


def lua_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def build(item_text, object_text, zone_text, sources):
    nodes = objects(object_text)
    maps = zone_maps(zone_text)
    found = items(item_text, nodes)
    lines = ['-- Gathering zones for WoW Forever, generated by tools/import_gathering.py - do not edit by hand.',
             '-- Node positions and drops: QuestieDB %s (%s), see SOURCES.json and SOURCE.md.' % (
                 sources['questiedb']['tag'], sources['questiedb']['commit'][:7]),
             '-- [item] = { prof, skill (lowest node), name, { { UiMapID, nodes, skill }, ... } }; zone names come from the client.',
             'local _,CP=...', 'CP.GatheringData={']
    total = 0
    for item, (name, drops) in sorted(found.items()):
        per_map, prof, low = {}, None, None
        for obj in drops:
            node, counts = nodes[obj]
            skill = MINING.get(node, HERBALISM.get(node))
            prof = 'mining' if node in MINING else 'herbalism'
            low = skill if low is None else min(low, skill)
            for area, n in counts.items():
                if area not in maps:
                    continue
                ui = maps[area][0]
                entry = per_map.setdefault(ui, [0, skill])
                entry[0] += n
                entry[1] = min(entry[1], skill)
        zones = sorted(per_map.items(), key=lambda kv: (-kv[1][0], kv[0]))[:TOP_ZONES]
        if not zones:
            continue
        total += 1
        z = ', '.join('{ %d, %d, %d }' % (ui, n, s) for ui, (n, s) in zones)
        lines.append('  [%d] = { %s, %d, %s, { %s } },' % (item, lua_str(prof), low, lua_str(name), z))
    lines.append('}')
    return ('\n'.join(lines) + '\n').encode('utf-8'), total


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--questiedb', type=Path, required=True, help='QuestieDB checkout at the pinned commit')
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    sources = json.loads((OUT / 'SOURCES.json').read_text())
    texts = {}
    for name in (ITEM_FILE, OBJECT_FILE, ZONE_FILE):
        data = (args.questiedb / name).read_bytes()
        if sha(data) != sources['questiedb']['files'][name]['sha256']:
            raise SystemExit('Checksum mismatch: ' + name)
        texts[name] = data.decode('utf-8')
    product, total = build(texts[ITEM_FILE], texts[OBJECT_FILE], texts[ZONE_FILE], sources)
    target = OUT / 'Gathering.lua'
    if args.check:
        if target.read_bytes().replace(b'\r\n', b'\n') != product:
            raise SystemExit('Generated gathering data differs from Gathering.lua')
    else:
        target.write_bytes(product)
    print(f'PASS: {total} gatherable items')


if __name__ == '__main__':
    main()
